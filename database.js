/*
===============================================================================
BANCO DE DADOS - CALCULADORA DE COMBUSTÃO
===============================================================================

UNIDADES
--------
massaMolar : kg/kmol
pcs        : MJ/kg
pci        : MJ/kg


===============================================================================
Cp(T) - EQUAÇÃO DE SHOMATE
===============================================================================

t = T / 1000

Cp° = A + B*t + C*t² + D*t³ + E/t²

onde:

T   = temperatura absoluta [K]
Cp° = capacidade calorífica molar [J/(mol.K)]


CONVERSÃO PARA BASE MÁSSICA:

Cp [kJ/(kg.K)] = Cp° [J/(mol.K)] / massaMolar [g/mol]


===============================================================================
MÉTODOS UTILIZADOS
===============================================================================

NIST_SHOMATE

    Coeficientes publicados diretamente pelo
    NIST Chemistry WebBook.


JOBACK_SHOMATE

    Cp ideal estimado pelo método Joback-Reid
    e convertido para a forma de Shomate.


Joback original:

Cp = a0 + a1*T + a2*T² + a3*T³


Conversão utilizada:

A = a0
B = 1000*a1
C = 1e6*a2
D = 1e9*a3
E = 0


Faixa Joback adotada:

298,15 K até 1000 K


IMPORTANTE
----------

- estimado = false:
  coeficientes Shomate obtidos diretamente de referência NIST.

- estimado = true:
  Cp calculado por Joback-Reid.

- SO2 permanece no banco porque é necessário como
  produto da combustão de compostos contendo enxofre.

===============================================================================
*/


